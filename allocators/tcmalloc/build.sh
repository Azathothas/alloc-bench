#!/bin/sh
. "$(dirname "$0")/../lib.sh"

prepare_out

case "$MODE" in
    prefixed)
        unsupported "tcmalloc exports no prefixed C allocation API; its supported interface is the malloc/operator-new replacement plus the C++ MallocExtension, so a #[global_allocator] shim has no C symbol to bind to."
        ;;
esac

if [ "$LIBC" = musl ]; then
    unsupported "upstream does not support musl; the Bazel build requires glibc-specific interfaces."
fi

command -v bazelisk >/dev/null 2>&1 || command -v bazel >/dev/null 2>&1 || \
    unsupported "neither bazelisk nor bazel is present in this image"

BAZEL=$(command -v bazelisk 2>/dev/null || command -v bazel)
export USE_BAZEL_VERSION="${TCMALLOC_BAZEL_VERSION:-8.6.0}"

cd "$SRC" || { echo "tcmalloc: cannot enter source dir $SRC" >&2; exit 1; }

PKG="$SRC/alloc_bench_preload"
mkdir -p "$PKG"
cat > "$PKG/BUILD" <<'BAZEL_BUILD'
# Generated by allocators/tcmalloc/build.sh. Do not edit in the source tree:
# it is overwritten on every build and the tree is a cache.
load("@rules_cc//cc:cc_binary.bzl", "cc_binary")

# A cc_binary with linkshared = 1 is the portable way to get a .so out of a
# Bazel graph whose allocator is a cc_library. The name must end in .so for
# Bazel to treat it as a shared library.
cc_binary(
    name = "libtcmalloc_allocbench.so",
    linkshared = 1,
    linkstatic = 1,
    deps = ["//tcmalloc"],
)
BAZEL_BUILD

# --nohome_rc so a runner's stray ~/.bazelrc cannot change what is built.
if ! "$BAZEL" --nohome_rc build -c opt //alloc_bench_preload:libtcmalloc_allocbench.so \
        >"$OUT/bazel.log" 2>&1; then
    if grep -qiE 'PKIX path building failed|certificate_unknown|unable to find valid certification path' "$OUT/bazel.log"; then
        unsupported "bazel could not fetch its module registry: the JVM rejected the TLS certificate for bcr.bazel.build (PKIX path building failed). bazelisk downloads its own JDK, whose trust store is not /etc/ssl/certs/ca-certificates.crt, so an extra CA trusted by the image is invisible to it. This is a property of this network, NOT of tcmalloc or of Bazel $USE_BAZEL_VERSION. On an unproxied host the build proceeds; here it needs a JDK in the image and the CA in that JDK's cacerts."
    fi
    unsupported "bazel build failed with USE_BAZEL_VERSION=$USE_BAZEL_VERSION: $(tail -5 "$OUT/bazel.log" | tr '\n' ' ')"
fi

so=$(
    {
        find -L "$SRC/bazel-bin" -type f -name 'libtcmalloc*.so' 2>/dev/null | sort
        find -L "$SRC/bazel-bin" -type f -name '*.so' 2>/dev/null | sort
    } | pick_elf_so
) || so=''
if [ -n "$so" ]; then
    cp "$so" "$SHARED"
    write_meta "" "bazel -c opt, USE_BAZEL_VERSION=$USE_BAZEL_VERSION; took $so"
    finish_so malloc free realloc calloc
    exit 0
fi

echo "--- what bazel left under bazel-bin (top 25 by size) ---" >&2
find -L "$SRC/bazel-bin" -type f \( -name '*.so*' -o -name '*.a' \) \
    -printf '%10s %p\n' 2>/dev/null | sort -rn | head -25 >&2
unsupported "bazel reported success for //alloc_bench_preload:libtcmalloc_allocbench.so and left no shared object under bazel-bin.  Upstream declares no shared-library target at the pinned commit -- 0 occurrences of cc_shared_library and 0 of linkshared across all four BUILD files -- so this recipe generates a cc_binary(linkshared = 1) over //tcmalloc; reaching here means that generated target produced no .so, not that the wrong upstream target was asked for. What bazel left is listed on stderr. docs/history/todo/mechanisms.md T-003."
