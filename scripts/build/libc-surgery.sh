#!/bin/sh
set -eu

ALLOC_ARCHIVE="${1:?usage: libc-surgery.sh <allocator-archive.a> <runner>}"
RUNNER="${2:?usage: libc-surgery.sh <allocator-archive.a> <runner>}"

[ -f "$ALLOC_ARCHIVE" ] || { echo "surgery: no such archive: $ALLOC_ARCHIVE" >&2; exit 2; }
[ -x "$RUNNER" ] || { echo "surgery: no such runner: $RUNNER" >&2; exit 2; }
command -v ar >/dev/null 2>&1 || { echo "surgery: ar not found" >&2; exit 2; }

SYMS='malloc,free,calloc,realloc,reallocarray,aligned_alloc,posix_memalign,memalign,valloc,pvalloc,malloc_usable_size,cfree,mallopt,malloc_trim,malloc_stats,mallinfo,mallinfo2,__libc_malloc,__libc_free,__libc_calloc,__libc_realloc,__libc_memalign,__libc_valloc,__libc_pvalloc,__libc_malloc_impl,__malloc_donate,__malloc_alloc_meta,__malloc_allzerop'

MUST_SURVIVE='fork pthread_create printf open memcpy'

# The allocator's archive must actually define malloc, or the surgery would
# delete libc's allocator and put nothing back -- which produces a libc.a that
# fails to link every program on the system.
if ! "$RUNNER" archive-check --archive "$ALLOC_ARCHIVE" --symbol malloc --expect-providers 1 >/dev/null 2>&1; then
    n=$("$RUNNER" archive-check --archive "$ALLOC_ARCHIVE" --symbol malloc --expect-providers 1 2>&1 | tail -1)
    echo "surgery: refusing to proceed: $ALLOC_ARCHIVE does not define malloc exactly once" >&2
    echo "  $n" >&2
    exit 1
fi

# Every libc.a on the image: the distribution's, and Rust's self-contained copy.
LIBCS=$(find /usr /lib /opt "${RUSTUP_HOME:-/usr/local/rustup}" "${CARGO_HOME:-/usr/local/cargo}" \
        -name 'libc.a' -type f 2>/dev/null | sort -u || true)

if [ -z "$LIBCS" ]; then
    echo "surgery: found no libc.a to patch" >&2
    exit 2
fi

patched=0
for libc in $LIBCS; do
    echo "surgery: $libc"

    # Keep one pristine copy per file so a re-run is idempotent rather than
    # splicing an allocator into an already-spliced archive.
    if [ ! -f "$libc.orig" ]; then
        cp "$libc" "$libc.orig"
    fi

    members=$("$RUNNER" ar-members --archive "$libc.orig" --symbols "$SYMS" 2>/dev/null || true)
    if [ -z "$members" ]; then
        echo "surgery: no member of $libc defines any allocation symbol; nothing to displace" >&2
        echo "surgery: this libc is not the one serving malloc, or its layout is unrecognised" >&2
        exit 1
    fi
    # `wc -l` is padded on some implementations and `tr` leaves the final
    # newline as a trailing space; both are trimmed so this line reads the same
    # everywhere. It is quoted rather than relying on word splitting to join it.
    n_members=$(echo "$members" | wc -l | tr -d ' ')
    member_list=$(echo "$members" | tr '\n' ' ')
    echo "surgery:   displacing $n_members member(s): ${member_list% }"

    for keep in $MUST_SURVIVE; do
        owner=$("$RUNNER" ar-members --archive "$libc.orig" --symbols "$keep" 2>/dev/null || true)
        [ -n "$owner" ] || continue
        for m in $members; do
            if [ "$m" = "$owner" ]; then
                echo "surgery: REFUSING to delete $m: it also defines '$keep', which is not allocator code." >&2
                echo "surgery: remove whichever symbol in SYMS matched it; see the note above SYMS." >&2
                exit 1
            fi
        done
    done

    tmp=$(mktemp -d)
    {
        echo "CREATE $tmp/libc.a"
        echo "ADDLIB $libc.orig"
        for m in $members; do
            echo "DELETE $m"
        done
        echo "ADDLIB $ALLOC_ARCHIVE"
        echo "SAVE"
        echo "END"
    } | ar -M

    ALIAS_CANDIDATES='__libc_malloc,__libc_free,__libc_calloc,__libc_realloc'
    missing=$("$RUNNER" ar-unresolved --archive "$tmp/libc.a" --symbols "$ALIAS_CANDIDATES") || {
        echo "surgery: could not ask $libc which aliases are unresolved" >&2
        rm -rf "$tmp"
        exit 2
    }
    if [ -n "$missing" ]; then
        echo "surgery:   $(echo "$missing" | tr '\n' ' ')-- referenced by musl, defined by nothing; synthesising"
        command -v "${CC:-cc}" >/dev/null 2>&1 || {
            echo "surgery: ${CC:-cc} not found, and these aliases must be compiled" >&2
            rm -rf "$tmp"
            exit 2
        }
        : > "$tmp/aliases.c"
        echo '/* Generated by scripts/build/libc-surgery.sh. Forwarding functions,' >> "$tmp/aliases.c"
        echo ' * not __attribute__((alias)): an alias target must live in the same' >> "$tmp/aliases.c"
        echo ' * translation unit, and malloc here comes from the archive. */' >> "$tmp/aliases.c"
        echo '#include <stddef.h>' >> "$tmp/aliases.c"
        for sym in $missing; do
            case "$sym" in
            __libc_malloc)
                echo 'void *malloc(size_t);' >> "$tmp/aliases.c"
                echo 'void *__libc_malloc(size_t n) { return malloc(n); }' >> "$tmp/aliases.c"
                ;;
            __libc_free)
                echo 'void free(void *);' >> "$tmp/aliases.c"
                echo 'void __libc_free(void *p) { free(p); }' >> "$tmp/aliases.c"
                ;;
            __libc_calloc)
                echo 'void *calloc(size_t, size_t);' >> "$tmp/aliases.c"
                echo 'void *__libc_calloc(size_t n, size_t m) { return calloc(n, m); }' >> "$tmp/aliases.c"
                ;;
            __libc_realloc)
                echo 'void *realloc(void *, size_t);' >> "$tmp/aliases.c"
                echo 'void *__libc_realloc(void *p, size_t n) { return realloc(p, n); }' >> "$tmp/aliases.c"
                ;;
            *)
                echo "surgery: REFUSING to synthesise '$sym': no forwarding definition is recorded for it." >&2
                echo "surgery: add one to libc-surgery.sh with its signature, or the archive is wrong." >&2
                rm -rf "$tmp"
                exit 1
                ;;
            esac
        done
        if ! "${CC:-cc}" -O2 -fPIC -std=c11 -c "$tmp/aliases.c" -o "$tmp/aliases.o" 2>"$tmp/cc.err"; then
            echo "surgery: could not compile the alias forwarders:" >&2
            sed 's/^/  /' "$tmp/cc.err" >&2
            rm -rf "$tmp"
            exit 1
        fi
        ar rcs "$tmp/aliases.a" "$tmp/aliases.o"
        {
            echo "CREATE $tmp/withaliases.a"
            echo "ADDLIB $tmp/libc.a"
            echo "ADDLIB $tmp/aliases.a"
            echo "SAVE"
            echo "END"
        } | ar -M
        if [ ! -s "$tmp/withaliases.a" ]; then
            echo "surgery: FAILED on $libc -- ar wrote no archive when adding the aliases" >&2
            rm -rf "$tmp"
            exit 1
        fi
        mv "$tmp/withaliases.a" "$tmp/libc.a"

        still=$("$RUNNER" ar-unresolved --archive "$tmp/libc.a" --symbols "$ALIAS_CANDIDATES")
        if [ -n "$still" ]; then
            echo "surgery: FAILED on $libc -- still unresolved after synthesis: $(echo "$still" | tr '\n' ' ')" >&2
            rm -rf "$tmp"
            exit 1
        fi
    fi

    broke=$("$RUNNER" ar-unresolved --archive "$tmp/libc.a" --baseline "$libc.orig") || {
        echo "surgery: could not ask $libc what the splice broke" >&2
        rm -rf "$tmp"
        exit 2
    }
    if [ -n "$broke" ]; then
        echo "surgery: FAILED on $libc -- the splice stranded symbols the rest of" >&2
        echo "surgery: libc.a still references and the replacement does not define:" >&2
        echo "$broke" | sed 's/^/    /' >&2
        echo "surgery: this libc has fused its allocator into unrelated machinery," >&2
        echo "surgery: or the replacement is missing an entry point it must supply." >&2
        rm -rf "$tmp"
        exit 1
    fi
    echo "surgery:   nothing stranded -- every symbol the deleted members defined"
    echo "surgery:   is either supplied or no longer referenced"

    if ! "$RUNNER" archive-check --archive "$tmp/libc.a" --symbol malloc --expect-providers 1; then
        echo "surgery: FAILED on $libc -- the patched archive does not define malloc exactly once" >&2
        rm -rf "$tmp"
        exit 1
    fi
    # ...and free, which is where a partial delete shows up: an archive can
    # easily end with one malloc and two frees if the members were split.
    if ! "$RUNNER" archive-check --archive "$tmp/libc.a" --symbol free --expect-providers 1; then
        echo "surgery: FAILED on $libc -- free is not defined exactly once after the splice" >&2
        rm -rf "$tmp"
        exit 1
    fi

    cp "$tmp/libc.a" "$libc"
    rm -rf "$tmp"
    patched=$((patched + 1))
done

echo "surgery: patched $patched libc.a copy/copies and verified each"
exit 0
